// UiServiceClient is a client for the ui.v1.UiService service.
type UiServiceClient interface {
	// GetWhoami names the authenticated account, so the panel can say whose view this is.
	GetWhoami(context.Context, *v1.GetWhoamiRequest) (*v1.GetWhoamiResponse, error)
	// ListOrgs lists the organisations the caller belongs to.
	ListOrgs(context.Context, *v1.ListOrgsRequest) (*v1.ListOrgsResponse, error)
	// ListRepos lists repositories the caller can see; `org` narrows to one.
	ListRepos(context.Context, *v1.ListReposRequest) (*v1.ListReposResponse, error)
	// ListReleases lists a repository's releases, newest first.
	ListReleases(context.Context, *v1.ListReleasesRequest) (*v1.ListReleasesResponse, error)
	// ListWorkflows lists a repository's workflows.
	ListWorkflows(context.Context, *v1.ListWorkflowsRequest) (*v1.ListWorkflowsResponse, error)
	// ListMirrored lists which of the caller's repositories the MIRROR has.
	ListMirrored(context.Context, *v1.ListMirroredRequest) (*v1.ListMirroredResponse, error)
	// Establish creates a repository on the forge and seeds it from its upstream. THE ONLY WRITE.
	Establish(context.Context, *v1.EstablishRequest) (*v1.EstablishResponse, error)
	// GetRepo describes one mirror repository: its default branch, branches and tags.
	GetRepo(context.Context, *v1.GetRepoRequest) (*v1.GetRepoResponse, error)
	// ListRefs lists everything browsable: every branch and tag.
	ListRefs(context.Context, *v1.ListRefsRequest) (*v1.ListRefsResponse, error)
	// ListDir lists one directory of the mirror.
	ListDir(context.Context, *v1.ListDirRequest) (*v1.ListDirResponse, error)
	// GetFile returns one file's text.
	GetFile(context.Context, *v1.GetFileRequest) (*v1.GetFileResponse, error)
	// GetPull returns a pull request's own facts.
	GetPull(context.Context, *v1.GetPullRequest) (*v1.GetPullResponse, error)
	// ListPullFiles returns what it changes, with per-file counts and patches.
	ListPullFiles(context.Context, *v1.ListPullFilesRequest) (*v1.ListPullFilesResponse, error)
	// GetPullDiff returns the whole change as one unified diff.
	GetPullDiff(context.Context, *v1.GetPullDiffRequest) (*v1.GetPullDiffResponse, error)
	// GetPullChecks returns CI status.
	GetPullChecks(context.Context, *v1.GetPullChecksRequest) (*v1.GetPullChecksResponse, error)
	// ListIssues lists issues and/or pull requests. ONE CALL FOR BOTH, because GitHub numbers them in
	// one sequence and the two lists are the same query with a different filter.
	ListIssues(context.Context, *v1.ListIssuesRequest) (*v1.ListIssuesResponse, error)
	// GetIssue returns an issue's own facts. It answers for a pull request too, and says which.
	GetIssue(context.Context, *v1.GetIssueRequest) (*v1.GetIssueResponse, error)
	// ListIssueComments returns its conversation, oldest first.
	ListIssueComments(context.Context, *v1.ListIssueCommentsRequest) (*v1.ListIssueCommentsResponse, error)
	// ListRuns lists recent runs for a repository, newest first.
	ListRuns(context.Context, *v1.ListRunsRequest) (*v1.ListRunsResponse, error)
	// GetRun returns one run's own facts.
	GetRun(context.Context, *v1.GetRunRequest) (*v1.GetRunResponse, error)
	// ListRunJobs returns where a run has got to: its jobs and each job's steps.
	ListRunJobs(context.Context, *v1.ListRunJobsRequest) (*v1.ListRunJobsResponse, error)
	// GetJobLog returns one job's log. A SEPARATE CALL because a run's logs are megabytes and a run
	// has several jobs; fetching them with the run would make opening the page cost the whole log
	// whether or not anybody read it.
	GetJobLog(context.Context, *v1.GetJobLogRequest) (*v1.GetJobLogResponse, error)
}

